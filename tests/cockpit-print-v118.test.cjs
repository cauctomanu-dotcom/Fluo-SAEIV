'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const read=f=>fs.readFileSync(f,'utf8');
const cockpit=read('v199-cockpit-responsive.js'),printer=read('v203-exploitation-print.js');
for(const name of ['v199-cockpit-responsive.js','v203-exploitation-print.js'])new vm.Script(read(name),{filename:name});
assert(cockpit.includes("html.v130-driving,html.v130-driving body{overflow:hidden!important}"),'GPS screen does not page-scroll in driving mode');
assert(cockpit.includes('grid-template-rows:minmax(0,1fr) 52px!important'),'GPS gets remaining height above short fixed action bar');
assert(cockpit.includes('display:grid!important;grid-template-columns:repeat(6,minmax(0,1fr))!important'),'driver controls are a fixed six-item row');
assert(cockpit.includes('overflow-x:hidden!important;overflow-y:hidden!important'),'never scroll primary navigation controls');
assert(!cockpit.includes('grid-template-columns:repeat(4,minmax(0,1fr))'),'narrow device no longer has 2 rows');
assert(!cockpit.includes('grid-template-columns:repeat(8,minmax(0,1fr))'),'replaces tiny 8 buttons');
assert(cockpit.includes("font-size:clamp(16px,2.2vw,21px)!important"),'next stop has legible text');
assert(cockpit.includes('b#v15NextDistance'),'next-stop distance prioritized');
assert(cockpit.includes('span{font-size:11px!important'),'delay labels visible');
assert(cockpit.includes('min-height:42px!important'),'touch targets kept');
assert(cockpit.includes('#driver.v185-view-line #v185Line'),'line thermometer accessible');
assert(cockpit.includes('state?.nav?.map?.invalidateSize?.()'),'Leaflet map resized after rotation');
assert(cockpit.includes('window.__fluoV16?.map3d?.resize?.()'),'3D map resized');
assert(!cockpit.includes('location.replace('),'no route/session changes');
assert(printer.includes("const allowed=()=>['dispatcher','admin']"),'only exploitation users can print');
assert(printer.includes("q('v165Date')?.value"),'current planning period used by default');
assert(printer.includes("q('v190End')?.value"),'end date used by default');
for(const table of ['saeiv_planning_days','saeiv_published_days','plan_items','profiles'])assert(printer.includes("'"+table+"'"),'print reads existing '+table);
assert(printer.includes(".eq('organization_id',cloud().profile.organization_id)"),'tenant filter applied to every day query');
assert(printer.includes(".eq('organization_id',c.profile.organization_id).eq('role','driver')"),'driver list tenant-scoped');
assert(printer.includes('data.set(key,{date:p.service_date,userId:p.driver_user_id,items:p.items||[],status:'),'drafts and published collected per driver/day');
assert(printer.includes('if(data.has(key))continue'),'legacy rows do not duplicate existing driver days');
assert(printer.includes("status:'BROUILLON — non publié'"),'draft labeled in printed material');
assert(printer.includes("status:'PUBLIÉ'"),'published distinct from drafts');
assert(printer.includes('window.print()'),'user-initiated print or save PDF');
assert(printer.includes('@media print'),'print optimized for A4');
assert(printer.includes('details'),'individual duty sheets option');
assert(printer.includes('summary'),'summary option');
assert(printer.includes('if(days<1||days>31)'),'limits excessive print range');
assert(!/\.insert\(|\.upsert\(|\.update\(|\.delete\(/.test(printer),'print module does not mutate schedule');
const sandbox={window:{},document:{readyState:'loading',addEventListener(){}},console};
vm.runInNewContext(printer,sandbox,{timeout:1000});
assert.equal(sandbox.window.MonSAEIVPrintV203.installed,true);
assert.equal(sandbox.window.MonSAEIVPrintV203.version,'1.0.118');
console.log('v1.0.119: mobile map readability, uninterrupted GPS and company-scoped draft/published planning print verified.');
