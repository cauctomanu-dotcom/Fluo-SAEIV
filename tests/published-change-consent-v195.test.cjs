'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const read=x=>fs.readFileSync(x,'utf8');
const p='supabase/migrations/';
const schema=read(p+'20261008200000_change_batches_v195.sql');
const propose=read(p+'20261008200100_batch_propose_v195.sql');
const finalize=read(p+'20261008200200_batch_finalize_v195.sql');
const guards=read(p+'20261008200300_batch_guards_v195.sql');
for(const s of ['saeiv_change_batches','batch_id uuid','response_exempt boolean','enable row level security','private.is_exploitation_for(organization_id)'])assert(schema.includes(s),s);
for(const s of ['private.current_org_id()','private.is_exploitation_for(o)','saeiv_planning_locks','for update','saeiv_published_days','saeiv_change_requests','saeiv_notifications','driver_unavailability','p_sick_driver','p_changes','exempt'])assert(propose.includes(s),s);
