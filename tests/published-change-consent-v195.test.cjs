const board=read(paths[0]),ui=read(paths[1]),inbox=read(paths[2]),sick=read(paths[3]),edit=read(paths[4]),automation=read(paths[5]);
assert(board.includes('data-v195-edit'));
assert(edit.includes('saeiv_propose_change')&&edit.includes('data-remove')&&edit.includes('saeiv_acquire_lock'));
assert(ui.includes('saeiv_finalize_change_batch')&&ui.includes('saeiv_cancel_change_batch')&&ui.includes('response_exempt'));
assert(ui.includes('!x.batch_id'),'no direct member finalize');
assert(inbox.includes('saeiv_respond_change')&&inbox.includes("p_response:response"));
assert(sick.includes('MonSAEIVSickApprovalV194.propose')||sick.includes('approval.propose(from,to,driver,reason)'));
assert(automation.includes('saeiv_propose_change_batch')&&automation.includes('saeiv_published_days')&&automation.includes('scoreCandidate'));
assert(!automation.includes("from('saeiv_published_days').update"),'cannot silently mutate official plans');
console.log('SAEIV 1.0.95: individual consent + batch all-accepted atomic publication contracts OK');
