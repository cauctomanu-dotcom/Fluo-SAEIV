assert(guards.includes('x.batch_id is not null'),'single finalize and cancel cannot bypass batch');
assert(guards.match(/x.batch_id is not null/g).length===2);
const paths=['v165-exploitation-board.js','v187-collaborative-planning.js','v188-driver-inbox.js','v178-sick-reassignment.js','v193-published-driver-edits.js','v194-sick-approval-batches.js'];
